-- Guarda la configuración de los gastos que se repiten cada mes.
CREATE TABLE recurring_expenses
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT                   NOT NULL,
    category_id  BIGINT                   NOT NULL,
    name         VARCHAR(100)             NOT NULL,
    amount       NUMERIC(12, 2)           NOT NULL,
    day_of_month SMALLINT                 NOT NULL,
    start_date   DATE                     NOT NULL,
    end_date     DATE,
    active       BOOLEAN                  NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
                                                   DEFAULT CURRENT_TIMESTAMP,

    -- Cada regla debe pertenecer a un usuario existente.
    CONSTRAINT fk_recurring_expenses_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    -- La categoría debe existir.
    -- El servicio comprobará que sea del propietario y de gasto.
    CONSTRAINT fk_recurring_expenses_category
        FOREIGN KEY (category_id) REFERENCES categories (id),

    -- El importe del gasto debe ser positivo.
    CONSTRAINT chk_recurring_expenses_amount
        CHECK (amount > 0),

    -- Guardamos el día solicitado, incluso si algunos meses son más cortos.
    CONSTRAINT chk_recurring_expenses_day
        CHECK (day_of_month BETWEEN 1 AND 31),

    -- La fecha final es opcional y no puede ser anterior a la inicial.
    CONSTRAINT chk_recurring_expenses_dates
        CHECK (end_date IS NULL OR end_date >= start_date)
);

-- Ayuda a consultar las reglas de un usuario.
CREATE INDEX idx_recurring_expenses_user
    ON recurring_expenses (user_id);