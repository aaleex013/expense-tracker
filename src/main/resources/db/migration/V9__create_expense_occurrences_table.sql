-- Cada fila representa un vencimiento concreto de un gasto recurrente.
CREATE TABLE expense_occurrences
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurring_expense_id BIGINT                   NOT NULL,
    user_id              BIGINT                   NOT NULL,
    category_id          BIGINT                   NOT NULL,
    name                 VARCHAR(100)             NOT NULL,
    amount               NUMERIC(12, 2)           NOT NULL,
    expiration_date      DATE                     NOT NULL,
    status               VARCHAR(10)              NOT NULL DEFAULT 'PENDING',
    movement_id          BIGINT,
    paid_at              TIMESTAMP WITH TIME ZONE,
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
                                                           DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_expense_occurrences_recurring
        FOREIGN KEY (recurring_expense_id)
            REFERENCES recurring_expenses (id),

    CONSTRAINT fk_expense_occurrences_user
        FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT fk_expense_occurrences_category
        FOREIGN KEY (category_id) REFERENCES categories (id),

    CONSTRAINT fk_expense_occurrences_movement
        FOREIGN KEY (movement_id) REFERENCES movements (id),

    -- Evita generar dos veces el mismo vencimiento.
    CONSTRAINT uk_expense_occurrences_recurring_date
        UNIQUE (recurring_expense_id, expiration_date),

    -- Un movimiento solo puede estar asociado a un vencimiento.
    CONSTRAINT uk_expense_occurrences_movement
        UNIQUE (movement_id),

    CONSTRAINT chk_expense_occurrences_amount
        CHECK (amount > 0),

    CONSTRAINT chk_expense_occurrences_status
        CHECK (status IN ('PENDING', 'PAID')),

    -- Un pendiente no tiene pago; un pagado debe tener movimiento y fecha.
    CONSTRAINT chk_expense_occurrences_payment
        CHECK (
            (
                status = 'PENDING'
                    AND movement_id IS NULL
                    AND paid_at IS NULL
                )
                OR
            (
                status = 'PAID'
                    AND movement_id IS NOT NULL
                    AND paid_at IS NOT NULL
                )
            )
);

-- Ayuda a consultar los vencimientos mensuales de un usuario.
CREATE INDEX idx_expense_occurrences_user_date
    ON expense_occurrences (user_id, expiration_date, id);