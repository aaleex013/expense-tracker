CREATE TABLE movements (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           user_id BIGINT NOT NULL,
                           category_id BIGINT NOT NULL,
                           type VARCHAR(10) NOT NULL,
                           amount NUMERIC(12, 2) NOT NULL,
                           movement_date DATE NOT NULL,
                           description VARCHAR(255),
                           created_at TIMESTAMP WITH TIME ZONE NOT NULL
                               DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT fk_movements_user
                               FOREIGN KEY (user_id) REFERENCES users(id),

                           CONSTRAINT fk_movements_category
                               FOREIGN KEY (category_id) REFERENCES categories(id),

                           CONSTRAINT chk_movements_type
                               CHECK (type IN ('INCOME', 'EXPENSE')),

                           CONSTRAINT chk_movements_amount
                               CHECK (amount > 0)
);

CREATE INDEX idx_movements_user_date
    ON movements (user_id, movement_date, id);

CREATE INDEX idx_movements_category
    ON movements (category_id);